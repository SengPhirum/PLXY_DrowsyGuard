#!/usr/bin/env bash
#
# plxy.sh - one entry point for the DrowsyGuard dev loop.
#
#   ./plxy.sh dev            build, flash and open the monitor  <- the usual one
#   ./plxy.sh help           every command
#
# Why this exists rather than calling idf.py directly:
#
#   1. ESP-IDF's export.ps1 derives its virtualenv name from whichever `python`
#      is first on PATH. This project ships a .venv on Python 3.13, so export
#      computes `idf5.5_py3.13_env`, an environment that was never installed,
#      and dies with "ESP-IDF Python virtual environment not found" - which
#      reads like a broken IDF install rather than a PATH-shadowing problem.
#      This script scrubs the project tree off PATH and asks idf_tools.py for
#      the real environment instead of guessing.
#   2. The board exposes two USB interfaces and neither behaves the way the
#      documentation assumes. On the CH343 UART bridge the reset line reaches EN
#      but not GPIO0, so nothing can drive it into download mode and flashing
#      fails with "Wrong boot mode detected (0x28)" - `flash` below detects that
#      and asks for one BOOT press. On the native USB-Serial/JTAG interface the
#      opposite holds: it sits in the ROM loader after every reset, so the
#      monitor shows nothing but "waiting for download". `port` says which one
#      the cable is in.
#   3. The interesting output of this firmware is not on the serial port at all
#      any more - it is a web page. `wifi`, `status` and `open` bridge that gap.
#
# Works in Git Bash on Windows (the environment this project is developed in).

set -o pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FW="$REPO/firmware/esp32s3"

# --------------------------------------------------------------------------- #
# pretty output
# --------------------------------------------------------------------------- #
if [ -t 1 ]; then
    B=$'\033[1m'; DIM=$'\033[2m'; R=$'\033[31m'; G=$'\033[32m'
    Y=$'\033[33m'; C=$'\033[36m'; Z=$'\033[0m'
else
    B=''; DIM=''; R=''; G=''; Y=''; C=''; Z=''
fi
say()  { printf '%s==>%s %s\n' "$C$B" "$Z" "$*"; }
ok()   { printf '%s  ok%s  %s\n' "$G" "$Z" "$*"; }
warn() { printf '%s  !!%s  %s\n' "$Y" "$Z" "$*"; }
die()  { printf '%s  xx%s  %s\n' "$R" "$Z" "$*" >&2; exit 1; }

# --------------------------------------------------------------------------- #
# ESP-IDF, run through PowerShell
# --------------------------------------------------------------------------- #
# ESP-IDF refuses to run under MSYS/MinGW outright - both idf.py and
# idf_tools.py bail with "MSys/Mingw is not supported" the moment they see
# MSYSTEM in the environment - and that guard is right: MSYS rewrites anything
# that looks like a path when it crosses into a native process, which corrupts
# the compiler command lines. So this script keeps the bash front end the
# project asked for and hands the actual build to PowerShell, which is the
# supported environment on Windows.
#
# The helper below is written to a temp file rather than squeezed through
# `powershell -Command`, because quoting a whole prelude through bash into
# PowerShell is its own bug farm. It does four things the plain
# `export.ps1` cannot do here:
#
#   * clears MSYSTEM, which PowerShell inherits from this shell and which would
#     trip the same guard one level down (a false positive - the process really
#     is PowerShell);
#   * rebuilds PATH from the Windows registry instead of inheriting bash's POSIX
#     PATH, which is meaningless to native tools;
#   * drops this repository from PATH, because its .venv is Python 3.13 and
#     export.ps1 derives the IDF virtualenv name from whichever python it finds
#     first - it then looks for idf5.5_py3.13_env, which was never installed,
#     and reports a missing virtualenv rather than a shadowing problem;
#   * picks the IDF-managed interpreter explicitly.

IDF_PS="${TMPDIR:-/tmp}/plxy-idf.ps1"

write_idf_helper() {
    [ -f "$IDF_PS" ] && [ "$IDF_PS" -nt "${BASH_SOURCE[0]}" ] && return 0
    cat >"$IDF_PS" <<'PS1'
# Generated by plxy.sh. Runs one ESP-IDF command in a sane environment.
param([Parameter(ValueFromRemainingArguments = $true)] $Args)
$ErrorActionPreference = 'Continue'

# Inherited from the calling shell; both would abort idf.py.
Remove-Item Env:MSYSTEM      -ErrorAction SilentlyContinue
Remove-Item Env:VIRTUAL_ENV  -ErrorAction SilentlyContinue
Remove-Item Env:PYTHONHOME   -ErrorAction SilentlyContinue
Remove-Item Env:PYTHONPATH   -ErrorAction SilentlyContinue

if (-not $env:IDF_TOOLS_PATH) { $env:IDF_TOOLS_PATH = 'C:\Espressif' }
if (-not $env:IDF_PATH) {
    $found = Get-ChildItem "$env:IDF_TOOLS_PATH\frameworks" -Directory -Filter 'esp-idf-v*' `
             -ErrorAction SilentlyContinue | Sort-Object Name | Select-Object -Last 1
    if (-not $found) { Write-Error 'ESP-IDF not found under $env:IDF_TOOLS_PATH\frameworks'; exit 2 }
    $env:IDF_PATH = $found.FullName
}

$py = Get-ChildItem "$env:IDF_TOOLS_PATH\python_env" -Directory -Filter 'idf*_py*_env' `
      -ErrorAction SilentlyContinue | Sort-Object Name | Select-Object -Last 1
if (-not $py) { Write-Error 'no ESP-IDF python env - re-run the IDF installer'; exit 2 }
$py = Join-Path $py.FullName 'Scripts\python.exe'

# The real Windows PATH, minus this repository (its .venv shadows IDF's python).
$base = @(
  [Environment]::GetEnvironmentVariable('Path', 'Machine'),
  [Environment]::GetEnvironmentVariable('Path', 'User')
) -join ';'
$base = ($base -split ';' | Where-Object { $_ -and $_ -notmatch 'PLXY_DrowsyGuard' }) -join ';'
$env:PATH = $base

# Tool locations come from idf_tools.py rather than being guessed.
$kv = & $py "$env:IDF_PATH\tools\idf_tools.py" export --format key-value 2>$null
if (-not $kv) { Write-Error 'idf_tools.py export produced nothing'; exit 2 }
foreach ($line in $kv) {
    if ($line -match '^([A-Z_0-9]+)=(.*)$') {
        $n = $Matches[1]; $v = $Matches[2]
        if ($n -eq 'PATH') { $env:PATH = $v.Replace('%PATH%', $base) }
        else { Set-Item -Path "env:$n" -Value $v }
    }
}

Set-Location $env:PLXY_FW

# --esptool: run esptool directly instead of idf.py. Needed because esptool's own
# reset sequences cannot reach download mode on this board, so flashing has to be told
# not to try (--before no_reset) once something else has put it there.
if ($Args.Count -gt 0 -and $Args[0] -eq '--esptool') {
    $rest = @($Args[1..($Args.Count - 1)])
    Remove-Item Env:ESPTOOL_CUSTOM_RESET_SEQUENCE -ErrorAction SilentlyContinue
    & $py -m esptool @rest
    exit $LASTEXITCODE
}

# --python: run a project script with ESP-IDF's interpreter, which has pyserial.
# scripts/board_reset.py is the caller - it drives the reset lines directly, which is
# what puts this board in the loader without the BOOT button.
if ($Args.Count -gt 0 -and $Args[0] -eq '--python') {
    $rest = @($Args[1..($Args.Count - 1)])
    & $py @rest
    exit $LASTEXITCODE
}

& $py "$env:IDF_PATH\tools\idf.py" @Args
exit $LASTEXITCODE
PS1
}

# Runs `idf.py <args>` in the firmware directory. Returns idf.py's exit code.
idf() {
    write_idf_helper
    PLXY_FW="$(cygpath -w "$FW")" \
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$(cygpath -w "$IDF_PS")" "$@"
}

# Runs `python -m esptool <args>`, same environment. Set PLXY_DIR to run it
# somewhere other than the firmware directory: `@flash_args` is resolved relative
# to the working directory of the PowerShell child, not of this shell, so a `cd`
# out here would have no effect on it.
esptool() {
    write_idf_helper
    PLXY_FW="$(cygpath -w "${PLXY_DIR:-$FW}")" \
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$(cygpath -w "$IDF_PS")" \
        --esptool "$@"
}

# True when the chip is already sitting in the ROM download loader. --before
# no_reset is the point: the default reset sequence would knock it back out.
in_download_mode() {
    esptool --chip esp32s3 -p "$1" --before no_reset --after no_reset \
        --connect-attempts 2 chip_id >/dev/null 2>&1
}

# Runs a project script with ESP-IDF's Python, which has pyserial. The project venv
# does not, and installing it there would be a second copy for one caller.
idf_python() {
    write_idf_helper
    PLXY_FW="$(cygpath -w "$REPO")" \
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$(cygpath -w "$IDF_PS")" \
        --python "$@"
}

# Put the chip in the ROM loader by driving the reset lines directly.
#
# This board's auto-reset lines are INVERTED relative to esptool's convention, which
# is the whole reason esptool cannot do it and why the instructions below used to be
# the only route. scripts/board_reset.py has the measurements. It verifies the ROM
# banner, so a false success is not possible.
enter_download_mode() {
    idf_python "scripts/board_reset.py" "$1" --download --quiet >/dev/null 2>&1
}

# --------------------------------------------------------------------------- #
# serial port
# --------------------------------------------------------------------------- #
# Prefer a USB-UART bridge over the ESP32-S3's native USB-Serial/JTAG: on this
# board only the bridge resets into the application reliably. Bluetooth virtual
# COM ports are excluded outright - they enumerate on most laptops and are never
# the board.
detect_port() {
    [ -n "$PLXY_PORT" ] && { echo "$PLXY_PORT"; return; }
    powershell.exe -NoProfile -Command '
      $devs = Get-CimInstance Win32_PnPEntity |
              Where-Object { $_.Name -match "\(COM\d+\)" -and $_.Name -notmatch "Bluetooth" }
      $rank = { param($n)
        if ($n -match "CH343|CH340|CP210|FTDI|Silicon Labs") { 0 }
        elseif ($n -match "JTAG|USB Serial Device")          { 1 }
        else                                                 { 2 } }
      $best = $devs | Sort-Object { & $rank $_.Name } | Select-Object -First 1
      if ($best -and $best.Name -match "\((COM\d+)\)") { $Matches[1] }
    ' 2>/dev/null | tr -d '\r\n'
}

port_table() {
    powershell.exe -NoProfile -Command '
      Get-CimInstance Win32_PnPEntity |
        Where-Object { $_.Name -match "\(COM\d+\)" } |
        ForEach-Object { $_.Name }
    ' 2>/dev/null | tr -d '\r'
}

require_port() {
    PORT="$(detect_port)"
    [ -n "$PORT" ] || die "no serial port found. Plug the board into the UART USB-C socket, then: ./plxy.sh port"
}

# --------------------------------------------------------------------------- #
# device HTTP API
# --------------------------------------------------------------------------- #
# 192.168.4.1 is fixed: it is the ESP-IDF SoftAP gateway address. Override with
# PLXY_HOST when the board is joined to a network in station mode instead.
HOST="${PLXY_HOST:-192.168.4.1}"

api() {
    local method="$1"; shift
    command -v curl >/dev/null || die "curl not found"
    curl -sS --max-time 5 -X "$method" "http://$HOST$1" || return 1
}

reachable() { curl -sS --max-time 3 -o /dev/null "http://$HOST/api/status" 2>/dev/null; }

wifi_setting() {  # wifi_setting WIFI_AP_PASSWORD
    sed -n "s/^#define $1[[:space:]]*\"\(.*\)\".*/\1/p" "$FW/main/board_wifi.h" | head -1
}

# --------------------------------------------------------------------------- #
# commands
# --------------------------------------------------------------------------- #
