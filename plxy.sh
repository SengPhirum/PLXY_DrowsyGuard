}

cmd_build()       { say "building"; idf build; }
cmd_reconfigure() { say "resolving components"; idf reconfigure; }
cmd_menuconfig()  { idf menuconfig; }
cmd_size()        { idf size; }
cmd_clean()       { say "clean"; idf clean; }

cmd_fullclean() {
    say "fullclean (build/ and sdkconfig)"
    idf fullclean
    rm -f "$FW/sdkconfig"
    ok "sdkconfig removed - the next build re-seeds it from sdkconfig.defaults"
}

# Flashing on this board is not the one-liner it is on most: its USB-UART bridge
# drives EN but not GPIO0, so no reset sequence can reach download mode and
# `idf.py flash` fails with "Wrong boot mode detected (0x28)". The chip has to be
# put in the loader by hand once, and then flashed with the reset lines left
# alone. So: check for the loader first, and only fall back to a normal flash.
#
# esptool directly rather than `idf.py flash`, for one reason: when the port it
# is given fails, idf.py walks every other COM port on the machine and buries the
# real error under a page of Bluetooth timeouts. Here `-p` means `-p`.
#
# $1 is esptool's --before: `no_reset` when the chip is already in the loader
# (touching the lines would knock it back out), `default_reset` otherwise.
flash_binaries() {
    [ -s "$FW/build/flash_args" ] || die "no build to flash - run ./plxy.sh build first"
    PLXY_DIR="$FW/build" esptool --chip esp32s3 -p "$PORT" -b 460800 \
        --before "$1" --after hard_reset write_flash "@flash_args"
}

cmd_flash() {
    require_port
    cmd_build || die "build failed"

    say "checking $PORT"
    if in_download_mode "$PORT"; then
        ok "already in the ROM loader - flashing without touching the reset lines"
        flash_binaries no_reset || die "flash failed"
    elif enter_download_mode "$PORT" && in_download_mode "$PORT"; then
        # The lines are inverted on this board, so the sequence esptool will not try
        # is the one that works. No BOOT press needed.
        ok "put it in the ROM loader over the serial lines - no BOOT press needed"
        flash_binaries no_reset || die "flash failed"
    else
        say "flashing $PORT"
        # esptool walks every other serial port when the one it was given fails,
        # which on a laptop means a screenful of Bluetooth timeouts between the
        # real error and the reader. Drop that chatter; keep everything else.
        flash_binaries default_reset 2>&1 | grep -vE \
            '^Serial port COM|failed to connect: (Could not open|Write timeout)|^Failed to get PID|^No serial ports found|^\(could not open port'
        if [ "${PIPESTATUS[0]}" -ne 0 ]; then
            echo
            warn "the board would not enter download mode, even over the raw lines"
            cat <<EOF

  esptool cannot do this on its own here, and ${B}scripts/board_reset.py${Z} - which
  drives the lines directly, with the inverted polarity this board actually uses -
  did not manage it either. Something is different about the connection this time.
  Put it in the loader by hand:

      1. ${B}Hold BOOT down${Z}   (may be labelled IO0)
      2. ${B}Tap RESET${Z}        (or unplug and replug USB) while still holding BOOT
      3. ${B}Release BOOT${Z}

  The board then waits in the loader indefinitely - there is no timing window to
  hit. Re-run ${B}./plxy.sh flash${Z} and it will detect the loader and go straight in.
EOF
            return 1
        fi
    fi
    ok "flashed"
    cmd_wifi
}

cmd_monitor() {
    require_port
    say "monitor on $PORT  ${DIM}(Ctrl+] to exit)${Z}"
    idf -p "$PORT" monitor
}

cmd_dev() {
    cmd_flash || return 1
    cmd_monitor
}

cmd_erase() {
    require_port
    warn "this erases NVS too, including the Wi-Fi calibration data"
    read -r -p "  erase all flash on $PORT? [y/N] " a
    case "$a" in [yY]*) idf -p "$PORT" erase-flash ;; *) echo "  skipped" ;; esac
}

cmd_port() {
    say "serial ports"
    local list; list="$(port_table)"
    [ -n "$list" ] || { warn "none found - is the cable a data cable, and in the UART socket?"; return 1; }
    echo "$list" | sed 's/^/     /'
    local p; p="$(detect_port)"
    echo
    if [ -n "$p" ]; then
        ok "will use $p"
        case "$(echo "$list" | grep "($p)")" in
            *CH343*|*CH340*|*CP210*|*FTDI*)
                echo "     ${DIM}USB-UART bridge - resets into the app reliably on this board${Z}" ;;
            *JTAG*|*"USB Serial Device"*)
                warn "this is the native USB-Serial/JTAG interface"
                echo "     ${DIM}On this board it re-enters the ROM download loader after every${Z}"
                echo "     ${DIM}reset, so the monitor may show only 'waiting for download'.${Z}"
                echo "     ${DIM}Move the cable to the other USB-C socket (the UART one).${Z}" ;;
        esac
    else
        warn "no candidate port"
    fi
}

cmd_wifi() {
    local ssid pw
    ssid="$(sed -n 's/^#define WIFI_AP_SSID_PREFIX[[:space:]]*"\(.*\)".*/\1/p' \
            "$FW/main/board_wifi.h" | head -1)"
    pw="$(wifi_setting WIFI_AP_PASSWORD)"
    cat <<EOF

${B}Watch the camera from your phone${Z}

  1. Power the board. You should hear ${B}three rising notes${Z}.
  2. On your phone: Settings > Wi-Fi, join

         network   ${B}${ssid}-XXXXXX${Z}   ${DIM}(XXXXXX = last 3 bytes of the board's MAC)${Z}
         password  ${B}${pw:-<open network>}${Z}

     Your phone will warn that the network has no internet. That is correct -
     the board ${B}is${Z} the network.
  3. Open ${B}http://${HOST}/${Z} in any browser.

  ${DIM}The exact SSID is printed in the boot log:  wifi: SoftAP "..." up on channel 6${Z}
  ${DIM}One live viewer at a time; a second phone gets still frames instead.${Z}
EOF
}

cmd_open() {
    say "opening http://$HOST/"
    reachable || warn "no answer from $HOST - are you joined to the board's Wi-Fi?"
    powershell.exe -NoProfile -Command "Start-Process 'http://$HOST/'" >/dev/null 2>&1 \
        || echo "  open http://$HOST/ manually"
}

cmd_status() {
    local j; j="$(api GET /api/status)" || die "no answer from $HOST - join the board's Wi-Fi first (./plxy.sh wifi)"
    if command -v python >/dev/null; then
        echo "$j" | python -c 'import json,sys; print(json.dumps(json.load(sys.stdin), indent=2))'
    else
        echo "$j"
    fi
}

cmd_watch() {
    command -v python >/dev/null || die "python not found"
    say "polling http://$HOST/api/status  ${DIM}(Ctrl+C to stop)${Z}"
    while true; do
        local j; j="$(api GET /api/status 2>/dev/null)"
        if [ -z "$j" ]; then
            printf '\r%s  waiting for the board...%s' "$Y" "$Z"
        else
            echo "$j" | python -c '
import json, sys
s = json.load(sys.stdin)
f, r, e = s["face"], s["risk"], s["eyes"]
print(f"fps {s[\"fps\"]:5.1f}  risk {r[\"score\"]:.2f}/{r[\"trigger\"]:.2f}"
      f"  perclos {e[\"perclos\"]:.2f}  eye {e[\"closed\"]:.2f}"
      f"  face {\"yes\" if f[\"found\"] else \" no\"}"
      f"  alerts {s[\"alert\"][\"count\"]}"
      f"  viewers {s[\"stream\"][\"viewers\"]}"
      f"  heap {s[\"mem\"][\"heap\"]//1024}k")'
        fi
        sleep 1
    done
}

cmd_snapshot() {
    local out="${1:-snapshot.jpg}"
    command -v curl >/dev/null || die "curl not found"
    curl -sS --max-time 10 -o "$out" "http://$HOST/api/snapshot" \
        || die "no answer from $HOST"
    [ -s "$out" ] || die "empty response - is the camera up? ./plxy.sh status"
    ok "wrote $out ($(wc -c <"$out" | tr -d ' ') bytes)"
}

cmd_alert() {
    local reason
    case "${1:-drowsy}" in
        drowsy|"")   reason=0 ;;
        microsleep)  reason=1 ;;
        yawn|yawning) reason=2 ;;
        nod|head_nod|headnod) reason=3 ;;
        *) die "reason must be one of: drowsy microsleep yawn nod" ;;
    esac
    api POST "/api/alert-test?reason=$reason" && echo
}

cmd_mute()   { api POST "/api/settings?muted=1" && echo; }
cmd_unmute() { api POST "/api/settings?muted=0" && echo; }

cmd_test() {
    local py="$REPO/.venv/Scripts/python.exe"
    [ -x "$py" ] || py=python
    say "pytest"
    ( cd "$REPO" && "$py" -m pytest tests/ -q )
}

cmd_diagrams() {
    local py="$REPO/.venv/Scripts/python.exe"
    [ -x "$py" ] || py=python
    say "regenerating figures"
    ( cd "$REPO" \
      && "$py" scripts/generate_tutorial_diagrams.py \
      && "$py" scripts/generate_step_diagrams.py \
      && "$py" scripts/generate_wiring_poster.py )
}

cmd_doctor() {
    say "toolchain"
    local ver
    ver="$(idf --version 2>&1 | tr -d '\r' | grep -oE 'v[0-9]+\.[0-9]+[^ ]*' | head -1)"
    if [ -n "$ver" ]; then
        ok "ESP-IDF  $ver"
    else
        warn "idf.py did not answer - run ./plxy.sh build to see why"
    fi

    echo; say "board"
    cmd_port || true
    local bin="$FW/build/drowsyguard_esp32s3.bin"
    echo
    if [ -f "$bin" ]; then
        ok "built    $(wc -c <"$bin" | tr -d ' ') bytes, $(date -r "$bin" '+%Y-%m-%d %H:%M')"
    else
        warn "no build yet - run ./plxy.sh build"
    fi

    echo; say "device"
    if reachable; then
        ok "reachable at http://$HOST/"
        cmd_status | grep -E '"(fps|camera|models|eye_model|ssid|ip)"' | sed 's/^/     /'
    else
        warn "not reachable at $HOST"
        echo "     ${DIM}Expected unless you are joined to the board's Wi-Fi: ./plxy.sh wifi${Z}"
    fi
}

