    monitor|mon)  shift; cmd_monitor "$@" ;;
    reconfigure)  shift; cmd_reconfigure "$@" ;;
    menuconfig)   shift; cmd_menuconfig "$@" ;;
    size)         shift; cmd_size "$@" ;;
    clean)        shift; cmd_clean "$@" ;;
    fullclean)    shift; cmd_fullclean "$@" ;;
    erase)        shift; cmd_erase "$@" ;;
    port|ports)   shift; cmd_port "$@" ;;
    wifi)         shift; cmd_wifi "$@" ;;
    open)         shift; cmd_open "$@" ;;
    status)       shift; cmd_status "$@" ;;
    watch)        shift; cmd_watch "$@" ;;
    snapshot|snap) shift; cmd_snapshot "$@" ;;
    alert)        shift; cmd_alert "$@" ;;
    mute)         shift; cmd_mute "$@" ;;
    unmute)       shift; cmd_unmute "$@" ;;
    test)         shift; cmd_test "$@" ;;
    diagrams)     shift; cmd_diagrams "$@" ;;
    doctor)       shift; cmd_doctor "$@" ;;
    help|-h|--help) cmd_help ;;
    *) die "unknown command '$1' - try ./plxy.sh help" ;;
esac
